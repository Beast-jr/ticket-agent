"""Wire the nodes together into a LangGraph.

Day 6 graph ("router" is a conditional edge: a fork, not a node):

    START
      |
      v
   classify
      |
      v
   retrieve <---------------------------------------+
      |                                              |
      v                                              |
   score_confidence                                  |
      |                                              |
      v                                              |
   [router] --- confidence >= HIGH ----------> draft ---------> END
      |
      +------- confidence < LOW -------------> escalate ------> END
      |
      +------- middle band, 2 attempts used -> escalate ------> END
      |
      +------- middle band, strong matches
      |        but labels disagree ----------> reconcile_category
      |                                              |
      |                                              v
      |                                          [router]  (same fork again)
      |
      +------- middle band, weak matches ----> rewrite_query ---+
                                                 (back to retrieve, then score again)

Every loop adds 1 to `attempts`, and the router escalates once attempts reaches 2,
so the graph can never run forever. A diagram generated by LangGraph is in docs/graph.md.
"""
from langgraph.graph import END, START, StateGraph

from agent.nodes import (classify, draft, escalate, reconcile_category, retrieve, rewrite_query,
                         router, score_confidence)
from agent.state import TicketState

# router() returns one of these names; the dict says which node each name leads to
ROUTES = {
    "draft": "draft",
    "reconcile_category": "reconcile_category",
    "rewrite_query": "rewrite_query",
    "escalate": "escalate",
}


def build_graph():
    graph = StateGraph(TicketState)
    graph.add_node("classify", classify)
    graph.add_node("retrieve", retrieve)
    graph.add_node("score_confidence", score_confidence)
    graph.add_node("draft", draft)
    graph.add_node("reconcile_category", reconcile_category)
    graph.add_node("rewrite_query", rewrite_query)
    graph.add_node("escalate", escalate)

    graph.add_edge(START, "classify")
    graph.add_edge("classify", "retrieve")
    graph.add_edge("retrieve", "score_confidence")
    graph.add_conditional_edges("score_confidence", router, ROUTES)
    graph.add_conditional_edges("reconcile_category", router, ROUTES)  # loop: decide again
    graph.add_edge("rewrite_query", "retrieve")                        # loop: search again
    graph.add_edge("draft", END)
    graph.add_edge("escalate", END)
    return graph.compile()


_app = None  # built once, reused


def run_ticket(text: str, ticket_id: str = "") -> TicketState:
    """Run one ticket through the graph and return the final state."""
    global _app
    if _app is None:
        _app = build_graph()
    start_state: TicketState = {
        "ticket_id": ticket_id,
        "text": text,
        "attempts": 0,
        "reconciled": False,
        "confidence_history": [],
        "status": "new",
        "steps_log": [],
    }
    return _app.invoke(start_state)


def path_taken(state: TicketState) -> list[str]:
    """The nodes that ran, in order (every node writes a steps_log line starting with its name)."""
    return [line.split(":", 1)[0] for line in state["steps_log"]]
