"""Wire the nodes together into a LangGraph.

Day 8 graph ("router", "after_check" and "after_human" are conditional edges: forks, not nodes):

    START
      |
      v
   classify
      |
      v
   retrieve <---------------------------------------+
      |                                              |
      v                                              |
   score_confidence                                  |
      |                                              |
      v                                              |
   [router] --- confidence < LOW, or 2 retries used --> escalate
      |                                                    ^   |
      +------- middle band, strong matches                 |   |
      |        but labels disagree ----> reconcile_category    |
      |                                  -> [router] (again)   |
      +------- middle band, weaker matches -> rewrite_query -+ |   (back to retrieve)
      |                                                        |
      +------- confidence >= HIGH ------> draft                |
                                            |                  |
                                            v                  |
                            +-------->   check                 |
                            |               |                  |
                            |               v                  |
                            |         [after_check]            |
                            |               |                  |
                            |               +-- not supported, first time --> redraft --+
                            |               |                                          |
                            +---------------|------------------------------------------+
                                            +-- not supported again ---------> escalate
                                            |
                                            +-- supported (status "replied") --> learn --> END

    escalate --> human_review  (the run PAUSES here and waits; only when a checkpointer is used)
                      |
                      v
                [after_human]
                      |
                      +-- approve / edit (status "replied_by_human") --> learn --> END
                      +-- reject (status "closed") ---------------------> END

Without a checkpointer (tests, evaluation scripts) escalate goes straight to END, because a run
can only pause if its state is saved. `learn` does nothing unless the run was started with
learn=True, and it only ever learns from replies that were sent.

Safety caps keep the graph finite:
- reconcile / rewrite each add 1 to `attempts`; the router escalates once attempts reaches 2.
- the self-check allows exactly ONE redraft (`redrafts`); a second failure escalates.
A diagram generated by LangGraph is in docs/graph.md.
"""
from langgraph.graph import END, START, StateGraph
from langgraph.types import Command

from agent.nodes import (after_check, after_human, check, classify, draft, escalate, human_review,
                         learn, reconcile_category, redraft, retrieve, rewrite_query, router,
                         score_confidence, validate_decision)
from agent.state import TicketState

# router() returns one of these names; the dict says which node each name leads to
ROUTES = {
    "draft": "draft",
    "reconcile_category": "reconcile_category",
    "rewrite_query": "rewrite_query",
    "escalate": "escalate",
}
CHECK_ROUTES = {"done": "learn", "redraft": "redraft", "escalate": "escalate"}
HUMAN_ROUTES = {"learn": "learn", "end": END}


def build_graph(checkpointer=None):
    """Build the graph. With a checkpointer every run is saved and escalated tickets wait for a human."""
    graph = StateGraph(TicketState)
    graph.add_node("classify", classify)
    graph.add_node("retrieve", retrieve)
    graph.add_node("score_confidence", score_confidence)
    graph.add_node("draft", draft)
    graph.add_node("check", check)
    graph.add_node("redraft", redraft)
    graph.add_node("reconcile_category", reconcile_category)
    graph.add_node("rewrite_query", rewrite_query)
    graph.add_node("escalate", escalate)
    graph.add_node("learn", learn)

    graph.add_edge(START, "classify")
    graph.add_edge("classify", "retrieve")
    graph.add_edge("retrieve", "score_confidence")
    graph.add_conditional_edges("score_confidence", router, ROUTES)
    graph.add_conditional_edges("reconcile_category", router, ROUTES)  # loop: decide again
    graph.add_edge("rewrite_query", "retrieve")                        # loop: search again
    graph.add_edge("draft", "check")
    graph.add_conditional_edges("check", after_check, CHECK_ROUTES)
    graph.add_edge("redraft", "check")                                 # loop: check the new reply
    if checkpointer is not None:
        graph.add_node("human_review", human_review)
        graph.add_edge("escalate", "human_review")
        graph.add_conditional_edges("human_review", after_human, HUMAN_ROUTES)
    else:
        graph.add_edge("escalate", END)
    graph.add_edge("learn", END)
    return graph.compile(checkpointer=checkpointer)


_app = None  # the graph without a checkpointer, built once and reused


def _fresh_state(text: str, ticket_id: str, learn_enabled: bool) -> TicketState:
    """A clean starting state. Every field is reset, so re-running a ticket id that already has a
    saved run never inherits leftovers (old replies, old summaries) from the earlier run."""
    return {
        "ticket_id": ticket_id, "text": text, "category": "", "priority": "", "classify_reason": "",
        "similar_tickets": [], "draft_reply": "", "used_ticket_ids": [], "analysis": {},
        "confidence": 0.0, "top_score": 0.0, "agreement": 0.0, "confidence_history": [],
        "attempts": 0, "reconciled": False, "redrafts": 0, "check_attempts": 0,
        "search_query": "", "check_result": "", "check_reason": "",
        "escalation_summary": "", "rejected_reply": "", "human_decision": {}, "final_reply": "",
        "learn_enabled": learn_enabled, "learned": False, "learned_ticket_id": "",
        "status": "new", "steps_log": [],
    }


def _config(ticket_id: str) -> dict:
    return {"configurable": {"thread_id": ticket_id}}  # thread_id = ticket id


def run_ticket(text: str, ticket_id: str = "", checkpointer=None, learn: bool = False) -> TicketState:
    """Run one ticket through the graph and return the final state.

    With a checkpointer the run is saved under thread_id = ticket_id (so ticket_id is required).
    If the ticket is escalated the run pauses at human_review and the returned dict contains an
    "__interrupt__" entry; finish it later with resume_ticket().
    learn=True lets the run add its final reply to the knowledge base."""
    global _app
    if checkpointer is None:
        if _app is None:
            _app = build_graph()
        return _app.invoke(_fresh_state(text, ticket_id, learn))
    if not ticket_id:
        raise ValueError("a ticket_id is required when a checkpointer is used (it is the thread_id)")
    return build_graph(checkpointer).invoke(_fresh_state(text, ticket_id, learn), _config(ticket_id))


def get_saved_state(ticket_id: str, checkpointer):
    """The saved snapshot of a ticket's run (.values = the state, .next = what runs next)."""
    return build_graph(checkpointer).get_state(_config(ticket_id))


def is_waiting_for_human(ticket_id: str, checkpointer) -> bool:
    return get_saved_state(ticket_id, checkpointer).next == ("human_review",)


def resume_ticket(ticket_id: str, decision: dict, checkpointer) -> TicketState:
    """Give a paused ticket its human decision and let the run continue.

    The decision is checked BEFORE anything is resumed, so a typo cannot damage the saved run."""
    decision = validate_decision(decision)
    if not is_waiting_for_human(ticket_id, checkpointer):
        raise ValueError(f"ticket {ticket_id!r} is not waiting for a human decision")
    return build_graph(checkpointer).invoke(Command(resume=decision), _config(ticket_id))


def list_paused(checkpointer) -> list[dict]:
    """All tickets that are waiting for a human decision, with their summaries."""
    rows = checkpointer.conn.execute("SELECT DISTINCT thread_id FROM checkpoints ORDER BY thread_id").fetchall()
    app = build_graph(checkpointer)
    paused = []
    for row in rows:
        snap = app.get_state(_config(row["thread_id"]))
        if snap.next == ("human_review",):
            v = snap.values
            paused.append({"ticket_id": row["thread_id"], "text": v.get("text", ""),
                           "category": v.get("category", ""), "priority": v.get("priority", ""),
                           "escalation_summary": v.get("escalation_summary", ""),
                           "rejected_reply": v.get("rejected_reply", "")})
    return paused


def path_taken(state: TicketState) -> list[str]:
    """The nodes that ran, in order (every node writes a steps_log line starting with its name)."""
    return [line.split(":", 1)[0] for line in state["steps_log"]]
